export type EffectDef = {
  slug: string;
  name: string;
  tagline: string;
  description: string;
  emoji: string;
  /** "built-in" = rendered with Sharp, "html" = HTML/CSS design rendered in Chromium, "motion" = AI video (needs a fal.ai key). */
  kind: "motion" | "built-in" | "html" | "business" | "personal";
  usesAi: boolean;
  /** Which AI step runs: none, an image edit, eye detection, or an HTML/CSS design. */
  ai: "none" | "edit" | "eyes" | "design";
  editKind?: EditKind;
  style: MotionStyle;
  needsFace?: boolean;
  /** Shows "move the eyes" sliders (Fire Eyes). */
  nudge?: boolean;
  /** Provider this effect depends on beyond the free keys. */
  requires?: "fal";
  /** For "edit" effects: true = still works without an AI image edit, in a clearly labelled basic mode. */
  editOptional?: boolean;
  /** Price in basic mode (when no AI image edit is available). */
  basicPriceUsd?: number;
  basicNote?: string;
  /** One-tap prompt ideas for effects where the customer describes what they want. */
  ideas?: { label: string; prompt: string }[];
  priceUsd: number;
  durationSeconds: number;
  categories: Category[];
  popular?: boolean;
  beta?: boolean;
  /** Public sample shown on the gallery (generated by `npm run samples`). */
  sample: string;
  /** Why it costs what it costs, shown next to the price. */
  priceNote: string;
  text?: { label: string; placeholder: string; maxLength: number; hint?: string; required?: boolean };
  themes: Choice[];
  defaultTheme: string;
  hasIntensity: boolean;
};

