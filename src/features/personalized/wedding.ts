import { rng } from "./text";
import { BASE, L, doc, textBlock, u, type Palette } from "./scene";

/**
 * Modern wedding greeting-card collection.
 * 15 distinct CSS-only designs; no external image assets required.
 * Keeps the existing Builder signature and textBlock integration.
 */
type W = number | "fluid";
type Builder = (name: string, w: W, greeting: string) => string;

const pal = (
    bg1: string,
    bg2: string,
    head: string,
    name: string,
    glow: string
): Palette => ({
    bg1,
    bg2,
    head,
    nameCss: `color:${name};text-shadow:0 0 ${u(1.2)} ${glow},0 ${u(.4)} ${u(.8)} rgba(0,0,0,.18)`,
    shadow: `0 ${u(.4)} ${u(1.2)} rgba(0,0,0,.25)`,
});

const delay = (i: number, n: number) => `-${((i * L) / n).toFixed(2)}s`;

function sparkles(seed: number, count: number, color = "#fff2c4"): string {
    const r = rng(seed);
    return Array.from({ length: count }, () =>
        `<i class="wc-spark" style="left:${(r() * 96).toFixed(1)}%;top:${(r() * 94).toFixed(1)}%;--d:${(r() * L).toFixed(2)}s;--s:${(.5 + r() * 1.5).toFixed(1)};--c:${color}"></i>`
    ).join("");
}

function petals(seed: number, count: number, colors: string[]): string {
    const r = rng(seed);
    return Array.from({ length: count }, (_, i) =>
        `<i class="wc-petal" style="left:${(r() * 100).toFixed(1)}%;--d:${(r() * L).toFixed(2)}s;--x:${(r() * 12 - 6).toFixed(1)};--c:${colors[i % colors.length]}"></i>`
    ).join("");
}

const COMMON = `
.wc-spark{position:absolute;width:calc(var(--u)*var(--s));height:calc(var(--u)*var(--s));border-radius:50%;background:var(--c);box-shadow:0 0 calc(var(--u)*1.5) var(--c);animation:wc-twinkle 2.8s ease-in-out infinite;animation-delay:var(--d);pointer-events:none}
@keyframes wc-twinkle{0%,100%{opacity:.15;transform:scale(.55)}50%{opacity:1;transform:scale(1.5)}}
.wc-petal{position:absolute;top:-8%;width:calc(var(--u)*1.4);height:calc(var(--u)*2.1);border-radius:100% 0 100% 0;background:var(--c);opacity:0;animation:wc-fall ${L}s linear infinite;animation-delay:var(--d);pointer-events:none}
@keyframes wc-fall{0%{transform:translate(0,-10%) rotate(0);opacity:0}12%{opacity:.9}100%{transform:translate(calc(var(--u)*var(--x)),calc(var(--u)*115)) rotate(420deg);opacity:0}}
.wc-frame{position:absolute;inset:7%;border:calc(var(--u)*.12) solid var(--frame,#d7bd83);pointer-events:none}
.wc-frame:after{content:"";position:absolute;inset:calc(var(--u)*.55);border:calc(var(--u)*.06) solid var(--frame2,#ffffff66)}
.wc-orn{position:absolute;left:50%;transform:translateX(-50%);font-size:calc(var(--u)*3);color:var(--accent,#e7c77d)}
.wc-orn.top{top:7%}.wc-orn.bottom{bottom:7%;transform:translateX(-50%) rotate(180deg)}
.wc-glow{position:absolute;inset:10%;border-radius:50%;background:radial-gradient(ellipse, var(--glow,#ffffff22),transparent 68%);pointer-events:none}
`;

/** Shared wrapper: keep greeting text generated by the existing textBlock(). */
function card(
    name: string, w: W, greeting: string, p: Palette,
    css: string, art: string,
    _unused?: number
): string {
    return doc(BASE(p) + COMMON + css, `${art}${textBlock(name, p, 52, greeting)}`, w);
}

